defmodule Mix.Tasks.Prism.GenTest do
  use ExUnit.Case, async: false

  @moduletag :tmp_dir

  alias Prism.Generator.Header

  setup %{tmp_dir: dir} do
    Mix.shell(Mix.Shell.Process)
    saved = Application.get_all_env(:prism_generator)
    Application.put_env(:prism_generator, :design, Prism.Generator.ExampleDesign)
    Application.put_env(:prism_generator, :targets, web: dir)

    on_exit(fn ->
      Mix.shell(Mix.Shell.IO)

      for {key, _} <- Application.get_all_env(:prism_generator),
          do: Application.delete_env(:prism_generator, key)

      Application.put_all_env(prism_generator: saved)
    end)
  end

  defp gen(args \\ []), do: Mix.Tasks.Prism.Gen.run(args)

  test "prism.gen writes every target's files as the fixtures, and can rerun", %{tmp_dir: dir} do
    gen()
    gen()

    for path <- ["tailwind.preset.js", "css/base.css", "css/components.css"] do
      assert Header.generated?(Path.join(dir, path))
      assert File.read!(Path.join(dir, path)) == File.read!("test/fixtures/web/#{path}")
    end

    assert dir |> File.ls!() |> Enum.sort() == ["css", "tailwind.preset.js"]
  end

  test "prism.gen writes the React target next to the web target", %{tmp_dir: dir} do
    Application.put_env(:prism_generator, :design, Prism.Generator.ExampleComponents)

    Application.put_env(:prism_generator, :targets,
      web: Path.join(dir, "web"),
      react: Path.join(dir, "react")
    )

    gen()
    gen(["--check"])

    for {path, body, _} <-
          Prism.Generator.React.files(Prism.Generator.ExampleComponents.__schema__()) do
      assert File.read!(Path.join([dir, "react", path])) ==
               File.read!("test/fixtures/react/#{path}")

      assert File.read!("test/fixtures/react/#{path}") =~ body
    end

    assert File.read!(Path.join(dir, "react/src/Button.tsx")) |> String.split("\n") |> hd() ==
             "// Generated by prism (mix prism.gen). Do not edit: change test/support/example_components.ex and regenerate."
  end

  test "prism.gen writes the design-tool target as the fixtures, and checks it", %{tmp_dir: dir} do
    Application.put_env(:prism_generator, :targets, design_tools: dir)

    gen()
    gen(["--check"])

    for path <- ["tokens.json", "tokens.css", "overview.svg"] do
      assert Header.generated?(Path.join(dir, path))

      assert File.read!(Path.join(dir, path)) ==
               File.read!("test/fixtures/design_tools/#{path}")
    end

    File.write!(Path.join(dir, "tokens.json"), "{}\n")
    assert_raise Mix.Error, ~r/not generated by prism/, fn -> gen() end
  end

  test "a generated file no target writes now is left over: --check fails, prism.gen removes it",
       %{tmp_dir: dir} do
    Application.put_env(:prism_generator, :design, Prism.Generator.ExampleComponents)
    Application.put_env(:prism_generator, :targets, react: dir)
    gen()

    # A renamed component's old file, hand-written files next to the generated ones,
    # and a file with a header in a folder the target doesn't write into.
    header = dir |> Path.join("src/Button.tsx") |> File.read!() |> String.split("\n") |> hd()
    File.write!(Path.join(dir, "src/OldButton.tsx"), header <> "\nexport {};\n")
    File.write!(Path.join(dir, "src/notes.ts"), "// hand-written\n")
    File.write!(Path.join(dir, "package.json"), "{\n  \"name\": \"kit\"\n}\n")
    File.mkdir_p!(Path.join(dir, "dist"))
    File.write!(Path.join(dir, "dist/Button.js"), header <> "\n")

    assert_raise Mix.Error,
                 ~r/out of date, run mix prism.gen: .*src\/OldButton.tsx \(no longer generated\)$/,
                 fn -> gen(["--check"]) end

    assert File.exists?(Path.join(dir, "src/OldButton.tsx"))

    gen()
    assert_received {:mix_shell, :info, ["* removing " <> removed]}
    assert removed =~ "src/OldButton.tsx"
    refute File.exists?(Path.join(dir, "src/OldButton.tsx"))

    for path <- ["src/notes.ts", "package.json", "dist/Button.js"],
        do: assert(File.exists?(Path.join(dir, path)))

    gen(["--check"])
  end

  test "only a file of a type the targets write, with exactly the header, is left over",
       %{tmp_dir: dir} do
    Application.put_env(:prism_generator, :design, Prism.Generator.ExampleComponents)
    Application.put_env(:prism_generator, :targets, react: dir)
    gen()

    src = &Path.join([dir, "src", &1])
    header = src.("Button.tsx") |> File.read!() |> String.split("\n") |> hd()

    # A note, a hand-edited copy whose first line only mentions the header's words,
    # a link to a generated file, and a header in a type the target doesn't write.
    File.write!(src.("NOTES.md"), "Generated by prism? No: these are my notes.\n")
    File.write!(src.("MyButton.tsx"), "// Copied from Generated by prism output, then edited\n")
    File.write!(src.("Edited.tsx"), header <> " Edited by hand.\n")
    File.ln_s!("Button.tsx", src.("Alias.tsx"))

    File.write!(
      src.("old.css"),
      "/* Generated by prism (mix prism.gen). Do not edit: change a.ex and regenerate. */\n"
    )

    gen(["--check"])
    gen()
    refute_received {:mix_shell, :info, ["* removing " <> _]}

    for name <- ~w(NOTES.md MyButton.tsx Edited.tsx Alias.tsx old.css),
        do: assert(match?({:ok, _}, File.lstat(src.(name))), name)
  end

  test "prism.gen removes nothing when a file it would write is hand-written", %{tmp_dir: dir} do
    gen()
    leftover = Path.join(dir, "css/old.css")
    File.write!(leftover, File.read!(Path.join(dir, "css/base.css")))
    File.write!(Path.join(dir, "tailwind.preset.js"), "hand-written\n")

    assert_raise Mix.Error, ~r/not generated by prism/, fn -> gen() end
    assert File.exists?(leftover)
  end

  test "the header names the design's file from the folder that holds it and the target",
       %{tmp_dir: dir} do
    gen()

    assert dir |> Path.join("css/base.css") |> File.read!() |> String.split("\n") |> hd() ==
             "/* Generated by prism (mix prism.gen). Do not edit: change test/support/example_design.ex and regenerate. */"
  end

  test "--check passes when the files are current and fails, writing nothing, when not",
       %{tmp_dir: dir} do
    assert_raise Mix.Error, ~r/out of date, run mix prism.gen: .*tailwind.preset.js/, fn ->
      gen(["--check"])
    end

    assert File.ls!(dir) == []

    gen()
    gen(["--check"])
    assert_received {:mix_shell, :info, ["All generated files are up to date."]}

    path = Path.join(dir, "css/base.css")
    File.write!(path, File.read!(path) <> "/* edited */\n")

    assert_raise Mix.Error, ~r/out of date, run mix prism.gen: .*css\/base.css/, fn ->
      gen(["--check"])
    end

    assert File.read!(path) =~ "/* edited */"
  end

  test "a hand-written file with a generated file's name is never overwritten", %{tmp_dir: dir} do
    path = Path.join(dir, "tailwind.preset.js")
    File.write!(path, "hand-written\n")

    assert_raise Mix.Error, ~r/not generated by prism; not overwriting it/, fn -> gen() end
    assert File.read!(path) == "hand-written\n"
  end

  test "prism.gen refuses a positional argument", %{tmp_dir: dir} do
    assert_raise Mix.Error, ~r/unexpected argument web/, fn -> gen(["web"]) end
    assert File.ls!(dir) == []
  end

  test "prism.gen needs a design module and known targets", %{tmp_dir: dir} do
    Application.delete_env(:prism_generator, :design)

    assert_raise Mix.Error, ~r/no design: set config :prism_generator, design: MODULE/, fn ->
      gen()
    end

    Application.put_env(:prism_generator, :design, Enum)
    assert_raise Mix.Error, ~r/Enum is not a design/, fn -> gen() end

    Application.put_env(:prism_generator, :design, Prism.Generator.ExampleDesign)
    Application.put_env(:prism_generator, :targets, [])
    assert_raise Mix.Error, ~r/no targets/, fn -> gen() end

    Application.put_env(:prism_generator, :targets, swift: dir)

    assert_raise Mix.Error,
                 ~r/unknown target :swift; known: \[:design_tools, :react, :web\]/,
                 fn -> gen() end

    assert File.ls!(dir) == []
  end

  test "the generators read only the design's data, not the schema's internals" do
    for path <-
          Path.wildcard("lib/**/*.ex") -- ["lib/schema.ex" | Path.wildcard("lib/schema/*.ex")] do
      code = path |> File.read!() |> String.replace(~r/@(module)?doc\s+"""(?s:.*?)"""/, "")
      refute code =~ "Prism.Generator.Schema.", "#{path} calls into Prism.Generator.Schema"
    end
  end
end

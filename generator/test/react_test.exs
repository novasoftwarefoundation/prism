defmodule Prism.Generator.ReactTest do
  use ExUnit.Case, async: true

  alias Prism.Generator.{ExampleComponents, Header, React, Web}

  # The example design's React package, reviewed and kept in test/fixtures/react with
  # its tests (`npm test` there type-checks and renders it). A change to what the
  # generator writes fails here until the fixtures are updated.
  test "the files for the example components equal the fixtures" do
    files = React.files(ExampleComponents.__schema__())

    for {path, body, _from} <- files do
      [_header, fixture] =
        String.split(File.read!("test/fixtures/react/#{path}"), "\n", parts: 2)

      assert body == fixture, "#{path} differs from test/fixtures/react/#{path}"
    end

    assert Enum.sort(for {path, _, _} <- files, do: path) ==
             Enum.sort(
               for path <- File.ls!("test/fixtures/react/src"), do: Path.join("src", path)
             )
  end

  # The CSS the render tests check the classes against.
  test "the fixtures' CSS is the web target's for the example components" do
    {path, css, from} =
      ExampleComponents.__schema__() |> Web.files() |> List.keyfind("css/components.css", 0)

    assert File.read!("test/fixtures/example_components/#{path}") ==
             Header.line(path, from) <> "\n" <> css
  end

  test "one file per component, an index and the helpers, all from the design's file" do
    files = React.files(ExampleComponents.__schema__())

    assert for({path, _, _} <- files, do: path) ==
             ~w(src/Button.tsx src/TextField.tsx src/TextArea.tsx src/Field.tsx
                src/RadioGroup.tsx src/Radio.tsx src/Select.tsx src/Spinner.tsx
                src/Checkbox.tsx src/Tag.tsx src/MessageBar.tsx src/StepIndicator.tsx
                src/helpers.ts src/index.ts)

    assert Enum.uniq(for {_, _, from} <- files, do: from) == [
             "test/support/example_components.ex"
           ]

    assert Header.line("src/Button.tsx", "a.ex") =~ ~r"\A// Generated by prism"
  end

  test "every line is within the generator's width of 100 columns" do
    for {path, body, _} <- React.files(ExampleComponents.__schema__()),
        line <- String.split(body, "\n") do
      assert String.length(line) <= 100, "#{path} has a line of #{String.length(line)}: #{line}"
    end
  end

  test "the class names are literals from the shared derivation" do
    button = body(ExampleComponents.__schema__(), "src/Button.tsx")

    assert button =~
             ~s|const variantClasses: Record<ButtonVariant, string> = {\n  primary: "kit-button--primary",|

    assert button =~ ~s|  accent: undefined,\n  danger: "kit-button--danger",|
    assert button =~ ~s|loading && "kit-button--loading"|
    assert button =~ ~s|present(icon) && "kit-button--with-icon"|
    assert button =~ ~s|{loading && <span className="kit-spinner kit-spinner--16" />}|
  end

  # A design of `body`, on the tokens of Prism.Generator.TokensOnly.
  defp design(body) do
    n = System.unique_integer([:positive])

    [{module, _}] =
      Code.compile_string("""
      defmodule ReactDesign#{n} do
        use Prism.Generator.Schema, tokens: Prism.Generator.TokensOnly
      #{body}
      end
      """)

    module.__schema__()
  end

  defp body(design, path) do
    {_, body, _} = design |> React.files() |> List.keyfind(path, 0)
    body
  end

  describe "designs Prism's doesn't have" do
    test "a state of a slot part is a prop that adds the part's class" do
      field =
        """
          component :field do
            part :label, foreground: :ink do
              state :invalid, foreground: "#C62828"
            end
            part :error_message, foreground: :ink
          end
        """
        |> design()
        |> body("src/Field.tsx")

      assert field =~ "  invalid?: boolean;\n"

      assert field =~
               ~s|"only-field__label",\n            invalid && "only-field__label--invalid",|
    end

    test "a disabled select disables its field, the form control among its parts" do
      select =
        """
          component :select do
            state :disabled, opacity: 0.5
            part :field, height: 40 do
              state :disabled, opacity: 0.4
            end
            part :listbox
            part :option
          end
        """
        |> design()
        |> body("src/Select.tsx")

      assert select =~ "/** Adds `only-select--disabled`; sets `disabled` on the field part. */"

      assert select =~
               ~s|<button type="button" disabled={disabled} className="only-select__field">|
    end

    test "a part that is another component has the classes of that component's defaults" do
      button =
        """
          component :spinner do
            style size: 24
            variants :size, default: :small do
              variant :small, size: 16
            end
          end

          component :button do
            part :label
            part :spinner, component: :spinner
          end
        """
        |> design()
        |> body("src/Button.tsx")

      # Without a loading state, the spinner is always there.
      assert button =~ ~s|      <span className="only-spinner only-spinner--small" />\n|
    end

    test "parts come in the design's order" do
      button =
        """
          component :button do
            part :icon
            part :label
          end
        """
        |> design()
        |> body("src/Button.tsx")

      [icon, label] =
        for part <- ~w(icon label), do: :binary.match(button, "only-button__#{part}")

      assert icon < label
    end
  end

  describe "a design the target can't render fails" do
    test "an unknown component or part, or no components" do
      assert_raise ArgumentError, ~r/the React target has no component :badge/, fn ->
        React.files(design("  component :badge do\n  end"))
      end

      assert_raise ArgumentError, ~r/the React target has no part :badge of :tag/, fn ->
        React.files(design("  component :tag do\n    part :label\n    part :badge\n  end"))
      end

      assert_raise ArgumentError, ~r/the design has no components/, fn ->
        React.files(Prism.Generator.TokensOnly.__schema__())
      end

      assert_raise ArgumentError, ~r/no `web` declaration/, fn ->
        React.files(%{ExampleComponents.__schema__() | web: nil})
      end
    end

    test "an axis whose type would be one of the component's own types" do
      for axis <- [:props, :own_props, :attributes, :other_attributes] do
        assert_raise ArgumentError,
                     ~r/can't name an axis of :button #{inspect(axis)}: its type, Button#{Macro.camelize(Atom.to_string(axis))}, is one of the component's own types/,
                     fn ->
                       React.files(
                         design(
                           "  component :button do\n    variants #{inspect(axis)} do\n      variant :a\n    end\n  end"
                         )
                       )
                     end
      end

      assert_raise ArgumentError,
                   ~r/its type, SelectOption, is one of the component's own types/,
                   fn ->
                     React.files(
                       design(
                         "  component :select do\n    part :listbox\n    part :option\n    variants :option do\n      variant :a\n    end\n  end"
                       )
                     )
                   end
    end

    test "a name that is a prop of every component, or a keyword" do
      assert_raise ArgumentError, ~r/can't name a prop of :tag "as"/, fn ->
        React.files(
          design("  component :tag do\n    variants :as do\n      variant :a\n    end\n  end")
        )
      end

      assert_raise ArgumentError, ~r/can't name a prop of :button "variantClasses"/, fn ->
        React.files(
          design(
            "  component :button do\n    variant :primary\n    variants :variant_classes do\n      variant :a\n    end\n  end"
          )
        )
      end

      assert_raise ArgumentError, ~r/can't name a prop of :tag "default"/, fn ->
        React.files(
          design(
            "  component :tag do\n    variants :default do\n      variant :a\n    end\n  end"
          )
        )
      end
    end
  end
end

defmodule Mix.Tasks.Prism.Gen do
  @shortdoc "Generates every target's files from the design"
  @moduledoc """
      mix prism.gen [--check]

  Generates the files of every configured target from the design:

      config :prism_generator,
        design: MyApp.Design,
        targets: [web: "../targets/web"]

  `design` is a module that uses `Prism.Generator.Schema`; `targets` maps each
  target to its folder. The targets are:

  - `web`: `Prism.Generator.Web` (a Tailwind preset, base CSS and, for a design
    with components, the component CSS);
  - `react`: `Prism.Generator.React` (a TSX file per component, for a package
    whose CSS is the web target's);
  - `design_tools`: `Prism.Generator.DesignTools` (a DTCG tokens file, the
    tokens as CSS custom properties, and an SVG overview of the design);
  - `swift`: `Prism.Generator.Swift` (a Swift package: the tokens, a style or
    view per component, and the fonts it bundles).

  Each file starts with a `Prism.Generator.Header` line (in a JSON file, the
  root's `$description`). A file that doesn't start with exactly that line,
  naming any design file, is hand-written and never overwritten.

  A target may also copy a file the design names, such as a font: a copy has no
  header and is written byte for byte. The folders a target copies into are the
  generator's: a copy replaces the file at its path (never a link or a folder),
  and a file there of a type the target copies (`.woff2`, `.txt`, …) that no
  target copies now is left over too. Other files there stay.

  A file that starts with exactly the header, of a type the targets write, in
  a folder a target writes into, which no target generates now (a renamed or
  removed component's), is left over: the task removes it. Everything else
  there stays: hand-written files without the header (a `package.json`, a
  note that mentions it), links, and what is in the folders below.

  With `--check`, nothing is written: the task fails when any file would change
  or is left over, for CI.
  """
  use Mix.Task

  alias Prism.Generator.Header

  @requirements ["compile"]

  # Every target module has `files/1`: a design's `__schema__/0` to
  # `[{path, body, design_file}]`, the design file being the one the body is made from;
  # a body `{:copy, source}` is a copy of the file at `source`, relative to the design's
  # project.
  @targets %{
    web: Prism.Generator.Web,
    react: Prism.Generator.React,
    design_tools: Prism.Generator.DesignTools,
    swift: Prism.Generator.Swift
  }

  @impl true
  def run(args) do
    {opts, rest} = OptionParser.parse!(args, strict: [check: :boolean])
    if rest != [], do: Mix.raise("unexpected argument #{Enum.join(rest, " ")}")

    schema = design!().__schema__()
    files = for {target, dir} <- targets!(), file <- files(target, dir, schema), do: file
    {copies, generated} = Enum.split_with(files, &match?({_, {:copy, _}}, &1))
    copies = Enum.map(copies, &read_copy!/1)

    leftovers = leftovers(generated, files) ++ leftover_copies(copies, files)

    if opts[:check] do
      check!(generated ++ copies, leftovers)
    else
      Enum.each(generated, &writable!/1)
      Enum.each(copies, &copyable!/1)
      # Removed first: on a case-insensitive file system a file renamed only in
      # case is the leftover's file.
      Enum.each(leftovers, &remove!/1)
      Enum.each(generated ++ copies, &write!/1)
    end
  end

  # `[{path, source}]` of one target, each source with a header naming the design
  # file it is made from, or `{:copy, file}` for a copy of `file`.
  defp files(target, dir, schema) do
    for {path, body, from} <- Map.fetch!(@targets, target).files(schema) do
      case body do
        {:copy, file} -> {Path.join(dir, path), {:copy, file}}
        body -> {Path.join(dir, path), Header.put(path, design_file(from, dir), body)}
      end
    end
  end

  # A copy's bytes, read before anything is written.
  defp read_copy!({path, {:copy, file}}) do
    case File.read(file) do
      {:ok, bytes} ->
        {path, bytes}

      {:error, reason} ->
        Mix.raise("can't copy #{file} to #{path}: #{:file.format_error(reason)}")
    end
  end

  defp writable!({path, _source}) do
    if File.exists?(path) and not Header.exact?(path),
      do: Mix.raise("#{path} exists and was not generated by prism; not overwriting it")
  end

  defp copyable!({path, _bytes}) do
    case File.lstat(path) do
      {:ok, %File.Stat{type: type}} when type != :regular ->
        Mix.raise("#{path} exists and is no regular file; not copying over it")

      _ ->
        :ok
    end
  end

  defp write!({path, source}), do: Mix.Generator.create_file(path, source, force: true)

  # The generated files no target writes now, in the folders the targets write into:
  # files, not links, of a type the targets write, that start with exactly the
  # header.
  defp leftovers(generated, files) do
    types = MapSet.new(generated, fn {path, _} -> Path.extname(path) end)
    for path <- candidates(generated, types, files), Header.exact?(path), do: path
  end

  # The copies no target makes now, in the folders the targets copy into: files, not
  # links, of a type the targets copy, that are no generated file.
  defp leftover_copies(copies, files) do
    types = MapSet.new(copies, fn {path, _} -> Path.extname(path) end)
    for path <- candidates(copies, types, files), not Header.exact?(path), do: path
  end

  # The regular files of `types` in the folders of `files`, that no target writes now.
  defp candidates(files, types, all) do
    written = MapSet.new(all, fn {path, _} -> Path.expand(path) end)

    for dir <- files |> Enum.map(&Path.dirname(elem(&1, 0))) |> Enum.uniq(),
        {:ok, names} <- [File.ls(dir)],
        name <- Enum.sort(names),
        path = Path.join(dir, name),
        Path.extname(path) in types,
        match?({:ok, %File.Stat{type: :regular}}, File.lstat(path)),
        Path.expand(path) not in written,
        do: path
  end

  defp remove!(path) do
    Mix.shell().info([:red, "* removing ", :reset, Path.relative_to_cwd(path)])
    File.rm!(path)
  end

  defp check!(files, leftovers) do
    stale =
      for({path, source} <- files, File.read(path) != {:ok, source}, do: path) ++
        for path <- leftovers, do: "#{path} (no longer generated)"

    if stale != [],
      do: Mix.raise("out of date, run mix prism.gen: #{Enum.join(stale, ", ")}")

    Mix.shell().info("All generated files are up to date.")
  end

  # The design's file as seen from the folder that holds both it and the target:
  # `theme/lib/tokens.ex` for a design in `theme/` and a target in `targets/web`.
  defp design_file(file, dir) do
    file = Path.expand(file)
    root = common_root(Path.split(file), Path.split(Path.expand(dir)))
    Path.relative_to(file, Path.join(root))
  end

  defp common_root([same | a], [same | b]), do: [same | common_root(a, b)]
  defp common_root(_, _), do: []

  defp design! do
    module =
      Application.get_env(:prism_generator, :design) ||
        Mix.raise("no design: set config :prism_generator, design: MODULE")

    unless Code.ensure_loaded?(module) and function_exported?(module, :__schema__, 0),
      do:
        Mix.raise(
          "#{inspect(module)} is not a design (a module that uses Prism.Generator.Schema)"
        )

    module
  end

  defp targets! do
    targets = Application.get_env(:prism_generator, :targets, [])

    if targets == [],
      do: Mix.raise("no targets: set config :prism_generator, targets: [web: PATH]")

    for {target, _dir} <- targets, not Map.has_key?(@targets, target) do
      Mix.raise(
        "unknown target #{inspect(target)}; known: #{inspect(Enum.sort(Map.keys(@targets)))}"
      )
    end

    targets
  end
end

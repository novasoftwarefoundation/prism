defmodule Prism.Generator.Header do
  @moduledoc """
  The first line of every generated file: it says the file is generated, by
  which command, and which design file to change instead. `mix prism.gen`
  writes it, and never overwrites a file without it.

  A JSON file has no comments: its header is the root group's
  `$description`, on the second line, after the object's `{`.
  """

  @marker "Generated by prism"

  @doc """
  The header line for the file at `path` (its extension picks the comment
  syntax), naming the design's file.
  """
  def line(path, design_file) do
    text = text(design_file, Path.extname(path))

    case Path.extname(path) do
      ext when ext in [".js", ".ts", ".tsx"] -> "// #{text}"
      ".css" -> "/* #{text} */"
      ".svg" -> "<!-- #{text} -->"
      ".json" -> ~s(  "$description": #{JSON.encode!(text)},)
      other -> raise ArgumentError, "no comment syntax for #{other} files"
    end
  end

  @doc """
  The file at `path` with its header: the header line above `body`, or in a
  JSON file, whose `body` is an object, as the object's first member.
  """
  def put(path, design_file, body) do
    case {Path.extname(path), body} do
      {".json", "{\n" <> members} -> "{\n" <> line(path, design_file) <> "\n" <> members
      {".json", _} -> raise ArgumentError, "a JSON body must be an object that starts with {\\n"
      _ -> line(path, design_file) <> "\n" <> body
    end
  end

  @doc "Whether the file at `path` starts with a header, so `mix prism.gen` may replace it."
  def generated?(path) do
    lines = path |> File.read!() |> String.split("\n", parts: 3)

    case {Path.extname(path), lines} do
      {".json", ["{", second | _]} ->
        String.starts_with?(second, ~s(  "$description": "#{@marker}))

      {_, [first | _]} ->
        String.contains?(first, @marker)
    end
  end

  defp text(design_file, ext) do
    text = "#{@marker} (mix prism.gen). Do not edit: change #{design_file} and regenerate."

    # One line that ends no comment: `*/`, or in an XML comment `--`.
    if String.contains?(text, "*/") or (ext == ".svg" and String.contains?(text, "--")) or
         Regex.match?(~r/[\x{0}-\x{1F}\x{2028}\x{2029}]/u, text),
       do: raise(ArgumentError, "#{inspect(design_file)} can't be written in a comment")

    text
  end
end

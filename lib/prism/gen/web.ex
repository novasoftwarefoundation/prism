defmodule Prism.Gen.Web do
  @moduledoc """
  Generates the web package from the spec: `tailwind.preset.js` and
  `css/base.css`, two of the files `@novasoftwarefoundation/prism` ships
  (`css/components.css` is still hand-written).

  The templates in `web/` hold the web mechanics (the plugin, the utilities,
  the line clamps); every design value comes from the spec. The output spells
  values the way prism 0.1.7 does, so consumers see no change: upper-case hex
  and two-decimal alphas in the preset, `0px` in text shadows, prettier's
  80-column wrap.
  """

  require EEx

  @dir Path.join(__DIR__, "web")
  @external_resource Path.join(@dir, "tailwind.preset.js.eex")
  @external_resource Path.join(@dir, "base.css.eex")

  EEx.function_from_file(:defp, :preset_js, Path.join(@dir, "tailwind.preset.js.eex"), [:spec])
  EEx.function_from_file(:defp, :base_css, Path.join(@dir, "base.css.eex"), [:spec])

  @headers %{
    "tailwind.preset.js" =>
      "// Generated by prism (mix prism.gen.web). Do not edit: change the spec and regenerate.",
    "css/base.css" =>
      "/* Generated by prism (mix prism.gen.web). Do not edit: change the spec and regenerate. */"
  }

  @doc "The header line of a generated file."
  def header(path), do: Map.fetch!(@headers, path)

  @doc "Returns `[{path, source}]` for the web package."
  def generate(%{tokens: tokens}) do
    for {path, source} <- [
          {"tailwind.preset.js", preset_js(tokens)},
          {"css/base.css", base_css(tokens)}
        ],
        do: {path, header(path) <> "\n" <> source}
  end

  # ------------------------------------------------------------- tokens

  defp tokens(spec, kind), do: for(%{kind: ^kind} = t <- spec, do: t)

  defp token(spec, kind, name),
    do: Enum.find(tokens(spec, kind), &(&1.name == name)) || raise("no #{kind} #{name}")

  # Follows aliases to the value.
  defp resolve(spec, kind, name) do
    case token(spec, kind, name).value do
      ref when is_atom(ref) -> resolve(spec, kind, ref)
      value -> value
    end
  end

  # JS object keys: bare when they're identifiers, quoted otherwise.
  defp key(name) when is_integer(name), do: Integer.to_string(name)

  defp key(name) do
    key = name |> to_string() |> String.replace("_", "-")
    if key =~ ~r/^[A-Za-z_$][A-Za-z0-9_$]*$/, do: key, else: ~s("#{key}")
  end

  # Groups as `// comment` blocks; `blank` puts an empty line between groups.
  defp js_groups(spec, kind, indent, blank, line_fun) do
    pad = String.duplicate(" ", indent)

    tokens(spec, kind)
    |> Enum.chunk_by(& &1.group)
    |> Enum.map(fn [first | _] = group ->
      comment = if first.group, do: ["#{pad}// #{first.group}\n"], else: []
      [comment | Enum.map(group, &"#{pad}#{line_fun.(&1)}\n")]
    end)
    |> Enum.intersperse(if(blank, do: "\n", else: []))
    |> IO.iodata_to_binary()
    |> String.trim_trailing("\n")
  end

  defp preset_colors(spec),
    do:
      js_groups(spec, :color, 6, true, &~s(#{key(&1.name)}: "#{resolve(spec, :color, &1.name)}",))

  defp preset_shadows(spec) do
    js_groups(spec, :shadow, 8, false, fn t ->
      css = shadow_css(spec, resolve(spec, :shadow, t.name), zero: "0", alpha: 2)
      ~s(#{key(t.name)}: "#{css}",)
    end)
  end

  defp px_lines(spec, kind, key_fun),
    do:
      Enum.map_join(tokens(spec, kind), "\n", &~s(        #{key(key_fun.(&1))}: "#{&1.value}px",))

  defp preset_spacing(spec), do: px_lines(spec, :space, & &1.key)
  defp preset_heights(spec), do: px_lines(spec, :height, & &1.key)
  defp preset_max_heights(spec), do: px_lines(spec, :max_height, & &1.name)

  defp preset_text_sizes(spec) do
    Enum.map_join(
      tokens(spec, :text),
      "\n",
      &~s(        #{key(&1.name)}: ["#{&1.size}px", "#{&1.line_height}px"],)
    )
  end

  # Fonts in runs of the same family, each run under the family's comment.
  defp by_family(spec, fun) do
    tokens(spec, :font)
    |> Enum.chunk_by(& &1.family)
    |> Enum.map_join("\n", fn [first | _] = fonts ->
      family = token(spec, :family, first.family)
      "        // #{family.doc}\n" <> Enum.map_join(fonts, "\n", &fun.(&1, family))
    end)
  end

  defp preset_font_families(spec) do
    by_family(spec, fn font, family ->
      ~s(        #{key(font.name)}: ["#{family.css_name}", "#{family.fallback}"],)
    end)
  end

  defp preset_font_classes(spec) do
    by_family(spec, fn font, family ->
      italic = if font[:italic], do: ~s(\n          "font-style": "italic",), else: ""

      """
              ".font-#{key_name(font.name)}": {
                "font-family": "#{family.css_name}, #{family.fallback}",
                "font-weight": "#{font.weight}",#{italic}
              },\
      """
    end)
  end

  defp key_name(name), do: name |> to_string() |> String.replace("_", "-")

  defp font_faces(spec) do
    for family <- tokens(spec, :family), face <- family.faces do
      {from, to} = face[:weights]

      %{
        family: family.css_name,
        doc: family.doc,
        file: face[:file],
        weights: "#{from} #{to}",
        style: face[:style],
        first: face == hd(family.faces)
      }
    end
  end

  # "Nunito (> 20px sizes)" → "> 20px", for base.css's face comments.
  defp sizes(doc), do: doc |> String.split("(") |> List.last() |> String.replace(" sizes)", "")

  # Wrapped like prettier does at 80 columns, as in 0.1.7.
  defp font_src(face) do
    url = ~s{url("../fonts/#{face.file}.woff2")}
    line = ~s{  src: #{url} format("woff2-variations");}

    if String.length(line) > 81,
      do: ~s{  src: #{url}\n    format("woff2-variations");},
      else: line
  end

  # `.prism-text-shadow` for :default, `.prism-text-shadow-<name>` for the others.
  defp text_shadows(spec) do
    for t <- tokens(spec, :text_shadow) do
      class =
        if t.name == :default,
          do: "prism-text-shadow",
          else: "prism-text-shadow-#{key_name(t.name)}"

      {class, shadow_css(spec, t.value, zero: "0px", spread: false)}
    end
  end

  # ------------------------------------------------------------ values

  # A shadow: [inset:, x:, y:, blur:, spread:, color: {color, alpha}]. `zero` is how 0 is
  # written; `alpha: 2` writes the alpha with two decimals (the preset's style).
  defp shadow_css(spec, shadow, opts) do
    zero = Keyword.fetch!(opts, :zero)
    length = fn n -> if n == 0, do: zero, else: "#{n}px" end
    {color, alpha} = shadow[:color]
    {r, g, b} = rgb(resolve(spec, :color, color))

    alpha =
      if opts[:alpha],
        do: :erlang.float_to_binary(alpha / 1, decimals: opts[:alpha]),
        else: number(alpha)

    lengths =
      [shadow[:x] || 0, shadow[:y] || 0, shadow[:blur] || 0] ++
        if(opts[:spread] == false, do: [], else: [shadow[:spread] || 0])

    inset = if shadow[:inset], do: "inset ", else: ""
    "#{inset}#{Enum.map_join(lengths, " ", length)} rgba(#{r}, #{g}, #{b}, #{alpha})"
  end

  defp rgb("#" <> hex) do
    <<r::8, g::8, b::8>> = Base.decode16!(hex, case: :mixed)
    {r, g, b}
  end

  defp number(n) when is_integer(n), do: Integer.to_string(n)
  defp number(n) when n == trunc(n), do: Integer.to_string(trunc(n))
  defp number(n), do: Float.to_string(n)
end

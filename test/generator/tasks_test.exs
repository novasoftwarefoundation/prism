defmodule Prism.Generator.TasksTest do
  use ExUnit.Case, async: false

  @moduletag :tmp_dir

  @design_args ["--design", "Prism.Generator.ExampleDesign"]

  setup do
    Mix.shell(Mix.Shell.Process)
    on_exit(fn -> Mix.shell(Mix.Shell.IO) end)
  end

  test "prism.gen.web writes the preset and base CSS and can rerun", %{tmp_dir: dir} do
    Mix.Tasks.Prism.Gen.Web.run(@design_args ++ ["--out", dir])
    Mix.Tasks.Prism.Gen.Web.run(@design_args ++ ["--out", dir])

    for path <- ["tailwind.preset.js", "css/base.css"] do
      assert Prism.Generator.generated?(Path.join(dir, path))
      assert File.read!(Path.join(dir, path)) == File.read!("test/generator/fixtures/web/#{path}")
    end

    assert dir |> File.ls!() |> Enum.sort() == ["css", "tailwind.preset.js"]
  end

  test "prism.gen.web takes the design and the output folder from the config", %{tmp_dir: dir} do
    saved = Application.get_all_env(:prism)
    Application.put_env(:prism, :design, Prism.Generator.ExampleDesign)
    Application.put_env(:prism, :out, dir)
    on_exit(fn -> Application.put_all_env(prism: saved) end)

    Mix.Tasks.Prism.Gen.Web.run([])
    assert Prism.Generator.generated?(Path.join(dir, "css/base.css"))
  end

  test "prism.gen.web needs a design module", %{tmp_dir: dir} do
    saved = Application.get_all_env(:prism)
    Application.delete_env(:prism, :design)
    on_exit(fn -> Application.put_all_env(prism: saved) end)

    assert_raise Mix.Error, ~r/no design: pass --design MODULE/, fn ->
      Mix.Tasks.Prism.Gen.Web.run(["--out", dir])
    end

    assert_raise Mix.Error, ~r/Enum is not a design/, fn ->
      Mix.Tasks.Prism.Gen.Web.run(["--design", "Enum", "--out", dir])
    end

    assert File.ls!(dir) == []
  end

  test "a hand-written file with a generated file's name is never overwritten", %{tmp_dir: dir} do
    path = Path.join(dir, "tailwind.preset.js")
    File.write!(path, "hand-written\n")

    assert_raise Mix.Error, ~r/not generated by prism; not overwriting it/, fn ->
      Mix.Tasks.Prism.Gen.Web.run(@design_args ++ ["--out", dir])
    end

    assert File.read!(path) == "hand-written\n"
  end

  test "prism.gen.web refuses a positional argument", %{tmp_dir: dir} do
    File.cd!(dir, fn ->
      assert_raise Mix.Error, ~r/unexpected argument out; use --out PATH/, fn ->
        Mix.Tasks.Prism.Gen.Web.run(@design_args ++ ["out"])
      end

      assert File.ls!(".") == []
    end)
  end

  test "the generators read only the design's data, not the schema's internals" do
    for path <-
          Path.wildcard("lib/generator/*.ex") -- ["lib/generator/schema.ex"],
        File.regular?(path) do
      code = path |> File.read!() |> String.replace(~r/@(module)?doc\s+"""(?s:.*?)"""/, "")
      refute code =~ "Prism.Generator.Schema.", "#{path} calls into Prism.Generator.Schema"
    end
  end
end

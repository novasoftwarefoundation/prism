defmodule PrismKit.GenTest do
  use ExUnit.Case, async: false

  @moduletag :tmp_dir

  @spec_args ["--spec", "PrismKit.FixtureSpec"]

  setup do
    Mix.shell(Mix.Shell.Process)
    on_exit(fn -> Mix.shell(Mix.Shell.IO) end)
  end

  test "prism.gen.web writes the preset and base CSS and can rerun", %{tmp_dir: dir} do
    Mix.Tasks.Prism.Gen.Web.run(@spec_args ++ ["--out", dir])
    Mix.Tasks.Prism.Gen.Web.run(@spec_args ++ ["--out", dir])

    for path <- ["tailwind.preset.js", "css/base.css"] do
      assert PrismKit.Gen.generated?(Path.join(dir, path))
      assert File.read!(Path.join(dir, path)) == File.read!("test/fixtures/web/#{path}")
    end

    assert dir |> File.ls!() |> Enum.sort() == ["css", "tailwind.preset.js"]
  end

  test "prism.gen.web takes the spec from the config", %{tmp_dir: dir} do
    Application.put_env(:prism_kit, :spec, PrismKit.FixtureSpec)
    on_exit(fn -> Application.delete_env(:prism_kit, :spec) end)

    Mix.Tasks.Prism.Gen.Web.run(["--out", dir])
    assert PrismKit.Gen.generated?(Path.join(dir, "css/base.css"))
  end

  test "prism.gen.web needs a spec module", %{tmp_dir: dir} do
    assert_raise Mix.Error, ~r/no spec: pass --spec MODULE/, fn ->
      Mix.Tasks.Prism.Gen.Web.run(["--out", dir])
    end

    assert_raise Mix.Error, ~r/Enum is not a spec/, fn ->
      Mix.Tasks.Prism.Gen.Web.run(["--spec", "Enum", "--out", dir])
    end

    assert File.ls!(dir) == []
  end

  test "a hand-written file with a generated file's name is never overwritten", %{tmp_dir: dir} do
    path = Path.join(dir, "tailwind.preset.js")
    File.write!(path, "hand-written\n")

    assert_raise Mix.Error, ~r/not generated by prism; not overwriting it/, fn ->
      Mix.Tasks.Prism.Gen.Web.run(@spec_args ++ ["--out", dir])
    end

    assert File.read!(path) == "hand-written\n"
  end

  test "prism.gen.web refuses a positional argument", %{tmp_dir: dir} do
    File.cd!(dir, fn ->
      assert_raise Mix.Error, ~r/unexpected argument out; use --out PATH/, fn ->
        Mix.Tasks.Prism.Gen.Web.run(@spec_args ++ ["out"])
      end

      assert File.ls!(".") == []
    end)
  end
end

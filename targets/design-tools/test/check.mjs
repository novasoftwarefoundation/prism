// Checks the design-tool files in each folder given on the command line: tokens.json
// against the DTCG 2025.10 JSON Schema and through two DTCG parsers (Terrazzo and
// Style Dictionary), tokens.css as CSS whose names are the DTCG paths, and
// overview.svg as standalone SVG. Exits with 1 on the first folder that fails.
import assert from "node:assert/strict";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import Ajv from "ajv";
import addFormats from "ajv-formats";
import { defineConfig, parse } from "@terrazzo/parser";
import StyleDictionary from "style-dictionary";
import postcss from "postcss";
import { XMLParser, XMLValidator } from "fast-xml-parser";

const here = fileURLToPath(new URL(".", import.meta.url));

// The DTCG 2025.10 schema, its files referring to each other by $id.
function dtcgValidator() {
  const ajv = new Ajv({ allErrors: true, strict: false });
  addFormats(ajv);
  const dir = join(here, "dtcg-2025.10");
  const files = (d) =>
    readdirSync(d).flatMap((f) =>
      statSync(join(d, f)).isDirectory() ? files(join(d, f)) : f.endsWith(".json") ? [join(d, f)] : [],
    );
  for (const file of files(dir)) ajv.addSchema(JSON.parse(readFileSync(file, "utf8")));
  return ajv.getSchema("https://www.designtokens.org/schemas/2025.10/format.json");
}

// Every token in a DTCG tree: `[path, token]`.
function tokensOf(tree, path = []) {
  return Object.entries(tree).flatMap(([key, value]) => {
    if (key.startsWith("$") || typeof value !== "object" || value === null) return [];
    return "$value" in value ? [[[...path, key], value]] : tokensOf(value, [...path, key]);
  });
}

async function checkJson(dir, validate) {
  const src = readFileSync(join(dir, "tokens.json"), "utf8");
  const json = JSON.parse(src);
  assert.match(json.$description, /^Generated by prism \(mix prism\.gen\)/, "the header is the root's $description");

  assert.ok(validate(json), `tokens.json is not DTCG 2025.10:\n${JSON.stringify(validate.errors?.slice(0, 5), null, 2)}`);

  const tokens = tokensOf(json);
  for (const [path, token] of tokens) assert.ok(token.$type, `${path.join(".")} has a $type`);

  // Terrazzo validates every value against its $type and resolves every reference.
  const config = defineConfig({}, { cwd: pathToFileURL(dir + "/") });
  const parsed = await parse([{ filename: pathToFileURL(join(dir, "tokens.json")), src }], { config });
  assert.equal(Object.keys(parsed.tokens).length, tokens.length, "Terrazzo reads every token");

  // Style Dictionary resolves every reference and names each token for CSS.
  const sd = new StyleDictionary({
    tokens: json,
    platforms: { css: { transformGroup: "css" } },
    log: { verbosity: "silent", warnings: "disabled", errors: { brokenReferences: "throw" } },
  });
  const { allTokens } = await sd.getPlatformTokens("css");
  assert.equal(allTokens.length, tokens.length, "Style Dictionary reads every token");
  return { json, sdNames: allTokens.map((t) => t.name) };
}

function checkCss(dir, { json, sdNames }) {
  const css = readFileSync(join(dir, "tokens.css"), "utf8");
  const root = postcss.parse(css);
  assert.equal(root.nodes.filter((n) => n.type === "rule").length, 1, "one rule");

  const rule = root.nodes.find((n) => n.type === "rule");
  assert.equal(rule.selector, ":root");

  const decls = rule.nodes.filter((n) => n.type === "decl");
  const names = decls.map((d) => d.prop);
  assert.ok(names.every((n) => n.startsWith("--")), "only custom properties");
  assert.equal(new Set(names).size, names.length, "no name twice");

  // The names are the DTCG paths after the prefix, as Style Dictionary names them.
  const prefix = names[0].slice(2, names[0].indexOf("-", 2));
  const fromJson = tokensOf(json).map(([path]) => `--${prefix}-${path.join("-")}`);
  assert.deepEqual(sdNames.map((n) => `--${prefix}-${n}`).sort(), [...fromJson].sort(), "Style Dictionary's names are the paths");

  // tokens.css has every token; only a length in percent is in it alone.
  const only = names.filter((n) => !fromJson.includes(n));
  assert.deepEqual(fromJson.filter((n) => !names.includes(n)), [], "every DTCG token is in tokens.css");
  for (const name of only) assert.match(decls.find((d) => d.prop === name).value, /^[\d.]+%$/, `${name} is in tokens.css alone`);

  for (const d of decls)
    for (const [, ref] of d.value.matchAll(/var\((--[\w-]+)\)/g)) assert.ok(names.includes(ref), `${d.prop} refers to ${ref}`);
}

function checkSvg(dir, { json }) {
  const svg = readFileSync(join(dir, "overview.svg"), "utf8");
  assert.equal(XMLValidator.validate(svg), true, "overview.svg is well-formed XML");
  assert.match(svg, /^<!-- Generated by prism \(mix prism\.gen\)/);

  const doc = new XMLParser({ ignoreAttributes: false, attributeNamePrefix: "", preserveOrder: true }).parse(svg);
  const root = doc.find((n) => n.svg);
  assert.ok(root, "the root is <svg>");
  assert.equal(root[":@"].xmlns, "http://www.w3.org/2000/svg");

  const elements = [];
  (function walk(nodes) {
    for (const node of nodes) {
      const name = Object.keys(node).find((k) => k !== ":@");
      if (!name || name === "#text" || name === "#comment") continue;
      elements.push({ name, attrs: node[":@"] ?? {} });
      walk(node[name]);
    }
  })(doc);

  const names = new Set(elements.map((e) => e.name));
  for (const banned of ["image", "style", "script", "foreignObject", "use", "a", "path"])
    assert.ok(!names.has(banned), `no <${banned}>`);

  const ids = new Set(elements.map((e) => e.attrs.id).filter(Boolean));
  for (const { attrs } of elements)
    for (const [key, value] of Object.entries(attrs)) {
      assert.ok(!/href$/.test(key), `no ${key}`);
      for (const [, ref] of String(value).matchAll(/url\(([^)]*)\)/g)) {
        assert.ok(ref.startsWith("#"), `${ref} is no external reference`);
        assert.ok(ids.has(ref.slice(1)), `${ref} is defined`);
      }
    }

  // Text is <text>, in the fonts the tokens name.
  const fonts = new Set(tokensOf(json).filter(([, t]) => t.$type === "fontFamily").map(([, t]) => t.$value));
  const texts = elements.filter((e) => e.name === "text");
  assert.ok(texts.length > 0);
  for (const { attrs } of texts) assert.ok(fonts.has(attrs["font-family"]), `font-family ${attrs["font-family"]} is a token's`);
}

const dirs = process.argv.slice(2).map((d) => resolve(d));
const validate = dtcgValidator();

for (const dir of dirs) {
  try {
    const tokens = await checkJson(dir, validate);
    checkCss(dir, tokens);
    checkSvg(dir, tokens);
    console.log(`ok ${dir}`);
  } catch (error) {
    console.error(`not ok ${dir}\n${error.stack}`);
    process.exit(1);
  }
}

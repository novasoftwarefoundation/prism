import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";

import { apply, preview } from "../src/collection.js";
import { nameKey, prismVariables, variableName } from "../src/variables.js";
import { Collection, designer } from "./designer.js";

const color = (hex, alpha = 1) => ({
  $type: "color",
  $value: { colorSpace: "srgb", components: [0, 0, 0], alpha, hex },
});
const size = (value, unit) => ({ $type: "dimension", $value: { value, unit } });

// A token file with a token of every kind tokens.json has.
const tokens = {
  $description: "Generated by prism (mix prism.gen).",
  color: {
    primary: color("#4272EF"),
    secondary: color("#FF5E5E"),
    grey1: color("#222222"),
    primarylight: color("#E3EAFD"),
    error: color("#DB1E1E"),
    delete: { $type: "color", $value: "{color.error}" },
    overlay: color("#000000", 0.5),
  },
  "font-family": {
    display: { $type: "fontFamily", $value: "Nunito", $extensions: { prism: { fallback: "sans-serif" } } },
  },
  "font-weight": { title0: { $type: "fontWeight", $value: 800 } },
  "font-size": { title0: size(64, "px") },
  "line-height": { title0: size(68, "px") },
  radius: { default: size(0.25, "rem") },
  typography: {
    title0: {
      $type: "typography",
      $value: {
        fontFamily: "{font-family.display}",
        fontWeight: "{font-weight.title0}",
        fontSize: "{font-size.title0}",
        lineHeight: 1.0625,
        letterSpacing: size(0, "px").$value,
      },
    },
  },
  shadow: {
    card: {
      $type: "shadow",
      $value: {
        color: color("#000000", 0.1).$value,
        offsetX: size(0, "px").$value,
        offsetY: size(5, "px").$value,
        blur: size(20, "px").$value,
        spread: size(0, "px").$value,
      },
    },
  },
};

// The site's collection: a hand copy of three of Prism's colors under the site's own
// names, and a variable of the site's own.
const site = () =>
  new Collection("Base collection", [
    ["Color", "primary", "#000000"],
    ["Color", "Secondary", "#ff5e5e"],
    ["Color", "Grey 1", "#111111"],
    ["Color", "brand", "#123456"],
  ]);

const byToken = (changes) => Object.fromEntries(changes.map((change) => [change.token, change]));

test("updates the site's variables by name, adds the missing ones to the same collection, and skips the rest", async () => {
  const collection = site();
  const { collection: name, changes } = await apply(designer([collection]), tokens);
  const actions = Object.fromEntries(changes.map(({ token, action }) => [token, action]));

  assert.equal(name, "Base collection");
  assert.deepEqual(actions, {
    "color.primary": "update",
    "color.secondary": "unchanged",
    "color.grey1": "update",
    "color.primarylight": "add",
    "color.error": "add",
    "color.delete": "add",
    "color.overlay": "add",
    "font-family.display": "add",
    "font-weight.title0": "add",
    "font-size.title0": "add",
    "line-height.title0": "add",
    "radius.default": "add",
    "typography.title0": "skip",
    "shadow.card": "skip",
  });
  assert.deepEqual(collection.writes, [
    ["set", "primary", "#4272EF"],
    ["set", "Grey 1", "#222222"],
    ["create", "Color", "primarylight", "#E3EAFD"],
    ["create", "Color", "error", "#DB1E1E"],
    ["create", "Color", "overlay", "#00000080"],
    ["create", "FontFamily", "font-family/display", "Nunito"],
    ["create", "Number", "font-weight/title0", 800],
    ["create", "Size", "font-size/title0", { value: 64, unit: "px" }],
    ["create", "Size", "line-height/title0", { value: 68, unit: "px" }],
    ["create", "Size", "radius/default", { value: 0.25, unit: "rem" }],
    // An alias stays an alias: color.delete is color.error.
    ["create", "Color", "delete", { alias: "error" }],
  ]);
  // The site's names stay, and its own variable is untouched.
  assert.deepEqual(byToken(changes)["color.grey1"].name, "Grey 1");
  assert.equal(collection.variable("brand").value, "#123456");
  assert.equal(byToken(changes)["typography.title0"].reason, "Webflow has no typography variable");
  assert.equal(byToken(changes)["shadow.card"].reason, "Webflow has no shadow variable");
});

test("a second run changes nothing", async () => {
  const collection = site();
  const webflow = designer([collection]);
  await apply(webflow, tokens);
  collection.writes.length = 0;

  const { changes } = await apply(webflow, tokens);

  assert.deepEqual(collection.writes, []);
  assert.deepEqual(
    changes.filter(({ action }) => action !== "unchanged").map(({ token }) => token),
    ["typography.title0", "shadow.card"],
  );
});

test("the preview shows what applying will do and changes nothing", async () => {
  const collection = site();
  const shown = await preview(designer([collection]), tokens);
  assert.deepEqual(collection.writes, []);

  const done = await apply(designer([collection]), tokens);
  const actions = ({ changes }) => changes.map(({ token, action, name }) => [token, action, name]);
  assert.deepEqual(actions(shown), actions(done));
});

test("never removes or renames a variable, and skips one whose type differs", async () => {
  const collection = new Collection("Base collection", [
    ["Number", "Primary", 1],
    ["Color", "grey1", "#000000"],
    ["Color", "Grey 1", "#000000"],
  ]);
  const { changes } = await apply(designer([collection]), tokens);

  assert.equal(byToken(changes)["color.primary"].action, "skip");
  assert.equal(
    byToken(changes)["color.primary"].reason,
    `the site's "Primary" is a Number variable, Prism's color.primary a Color`,
  );
  assert.equal(byToken(changes)["color.grey1"].action, "skip");
  assert.match(byToken(changes)["color.grey1"].reason, /2 variables with this name: "grey1", "Grey 1"/);
  assert.deepEqual(
    collection.writes.filter(([write, , name]) => write !== "create" || ["primary", "grey1"].includes(name)),
    [],
  );
  assert.deepEqual(
    collection.variables.slice(0, 3).map(({ name, value }) => [name, value]),
    [
      ["Primary", 1],
      ["grey1", "#000000"],
      ["Grey 1", "#000000"],
    ],
  );
});

test("an alias whose variable is skipped is skipped", async () => {
  const collection = new Collection("Base collection", [["Size", "error", { value: 1, unit: "px" }]]);
  const { changes } = await apply(designer([collection]), tokens);

  assert.equal(byToken(changes)["color.delete"].action, "skip");
  assert.equal(byToken(changes)["color.delete"].reason, "it refers to color.error, which is skipped");
  assert.equal(collection.variable("delete"), undefined);
});

test("an alias that points elsewhere, or a custom value, is updated", async () => {
  const collection = new Collection("Base collection", [
    ["Color", "error", "#DB1E1E"],
    ["Color", "primary", { type: "custom", value: "color-mix(in srgb, red, blue)" }],
  ]);
  await collection.createColorVariable("delete", collection.variable("primary"));
  collection.writes.length = 0;
  const { changes } = await apply(designer([collection]), tokens);

  assert.equal(byToken(changes)["color.primary"].action, "update");
  assert.equal(byToken(changes)["color.delete"].action, "update");
  assert.equal(collection.variable("delete").value, collection.variable("error"));
  assert.equal(collection.variable("primary").value, "#4272EF");
});

test("writes into the collection that holds Prism's variables", async () => {
  const other = new Collection("Base collection", [["Color", "brand", "#123456"]]);
  const prism = new Collection("Prism", [["Color", "primary", "#000000"]]);
  await apply(designer([other, prism]), tokens);

  assert.deepEqual(other.writes, []);
  assert.equal(prism.variable("primarylight").value, "#E3EAFD");
});

test("writes into the default collection when none holds Prism's variables", async () => {
  const base = new Collection("Base collection");
  const theme = new Collection("Theme", [["Color", "brand", "#123456"]]);
  await apply(designer([base, theme]), tokens);

  assert.deepEqual(theme.writes, []);
  assert.equal(base.variable("primary").value, "#4272EF");
});

test("changes nothing when two collections hold as many of Prism's variables", async () => {
  const one = new Collection("One", [["Color", "primary", "#000000"]]);
  const two = new Collection("Two", [["Color", "grey1", "#000000"]]);
  await assert.rejects(
    apply(designer([one, two]), tokens),
    /Collections One and Two hold as many of Prism's variables each/,
  );
  assert.deepEqual([...one.writes, ...two.writes], []);
});

test("changes nothing where Webflow doesn't allow changing variables", async () => {
  const collection = site();
  await assert.rejects(apply(designer([collection], { canModifyVariables: false }), tokens), /Design mode/);
  assert.deepEqual(collection.writes, []);
});

test("a change Webflow refuses is skipped with its reason, and the others are made", async () => {
  const collection = new Collection("Base collection", [["Color", "primarylight", "#E3EAFD"]]);
  collection.createColorVariable = async () => {
    throw new Error("DuplicateValue");
  };
  const { changes } = await apply(designer([collection]), tokens);

  assert.equal(byToken(changes)["color.error"].reason, "Webflow refused it: DuplicateValue");
  assert.equal(byToken(changes)["color.delete"].reason, "Webflow refused it: color.error wasn't written");
  assert.equal(byToken(changes)["font-size.title0"].action, "add");
  assert.deepEqual(collection.variable("font-size/title0").value, { value: 64, unit: "px" });
});

test("names: a color by its name, another token in its group's folder; keys ignore case, spaces and dashes", () => {
  assert.equal(variableName(["color", "grey1"]), "grey1");
  assert.equal(variableName(["font-size", "title0"]), "font-size/title0");
  assert.equal(nameKey("Grey 1"), nameKey("grey1"));
  assert.equal(nameKey("grey-1"), nameKey("grey1"));
  assert.notEqual(nameKey("font-size/title0"), nameKey("line-height/title0"));
  assert.notEqual(nameKey("font-size/title0"), nameKey("fontsizetitle0"));
});

test("a size in a unit Webflow has no size variable for is skipped", () => {
  const { skipped } = prismVariables({ radius: { round: size(50, "%") } });
  assert.deepEqual(skipped, [{ token: "radius.round", reason: "Webflow has no size in %" }]);
});

test("Prism's tokens.json: the site's hand copy is updated by name, and every other token is added or skipped", async () => {
  const prismTokens = JSON.parse(readFileSync(new URL("../../design-tools/tokens.json", import.meta.url), "utf8"));
  const { variables, skipped } = prismVariables(prismTokens);

  const keys = variables.map(({ name }) => nameKey(name));
  assert.equal(new Set(keys).size, keys.length, "no two tokens are one variable");
  assert.deepEqual(
    new Set(skipped.map(({ reason }) => reason)),
    new Set(["Webflow has no typography variable", "Webflow has no shadow variable"]),
  );

  const handCopy = ["primary", "secondary", "tertiary", "Grey 1", "grey-2", "grey 3", "Grey4", "grey 5", "grey 6"];
  const collection = new Collection(
    "Base collection",
    handCopy.map((name) => ["Color", name, "#000000"]),
  );
  const { changes } = await apply(designer([collection]), prismTokens);

  const updated = changes.filter(({ action }) => action === "update").map(({ name }) => name);
  assert.deepEqual(updated, handCopy);
  assert.equal(collection.variables.length, variables.length, "one variable per token Webflow can hold");
  assert.equal(collection.variable("Grey 1").value, prismTokens.color.grey1.$value.hex);
});
